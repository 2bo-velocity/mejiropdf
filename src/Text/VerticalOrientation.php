    /** The class for a code point, or 0 when it is set upright unchanged. */
    public static function of(int $codePoint): int
    {
        $low = 0;
        $high = \count(self::RANGES) - 1;

        while ($low <= $high) {
            $mid = \intdiv($low + $high, 2);
            [$start, $end, $class] = self::RANGES[$mid];
            if ($codePoint < $start) {
                $high = $mid - 1;
            } elseif ($codePoint > $end) {
                $low = $mid + 1;
            } else {
                return $class;
            }
        }

        return 0;
    }
