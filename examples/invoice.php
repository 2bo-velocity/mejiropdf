<?php

declare(strict_types=1);

/**
 * MejiroPDF — streaming table + page numbers example.
 *
 * Generates a multi-page report whose detail table breaks across pages, with an
 * auto page-number footer ("N / TOTAL") and the credit on the opposite side.
 *
 * Run on PHP 8.3+:  php examples/invoice.php
 */

require __DIR__ . '/../vendor/autoload.php';

use MejiroPDF\Document;
use MejiroPDF\Font\StandardFont;
use MejiroPDF\Page\Alignment;
use MejiroPDF\Page\PageNumberOptions;
use MejiroPDF\Table\Column;

$pdf = new Document();
$pdf->setPageNumbers(new PageNumberOptions(
    format: 'Page {PAGE} of {TOTAL}',
    alignment: Alignment::RIGHT,   // credit auto-lands on the left
));

$pdf->addPage()
    ->text(20, 25, 'Sales Report', size: 22.0, color: '#06B6D4')
    ->text(20, 33, 'Generated by MejiroPDF', size: 11.0);

$table = $pdf->table(
    [
        new Column('#', 15, Alignment::CENTER),
        new Column('Item', 95, Alignment::LEFT),
        new Column('Qty', 25, Alignment::RIGHT),
        new Column('Price', 35, Alignment::RIGHT),
    ],
    x: 20,
    y: 42,
    fontSize: 9.0,
)->header(['#', 'Item', 'Qty', 'Price']);

// Enough rows to force an automatic page break with header repeat.
for ($i = 1; $i <= 120; $i++) {
    $table->row([
        (string) $i,
        "Product line item number {$i}",
        (string) \random_int(1, 40),
        '$' . \number_format(\random_int(100, 99999) / 100, 2),
    ]);
}

$pdf->save(__DIR__ . '/invoice.pdf');

echo "Wrote invoice.pdf ({$pdf->pageCount()} pages).\n";
